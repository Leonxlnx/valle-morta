def gait(ph, G, dz=0.0):
    p = base(); st = G['v'] * G['T'] / LS
    c = lambda o, k=1: np.cos(2 * pi * k * (ph - o))             # peaks at phase o (k-th harmonic)
    for i, s in enumerate('LR'):
        u = (ph - G['ph0'][i]) % 1.0
        y, lift, pitch, tw = _foot(u, G['D'][i], G['yf'][i], st, -G['hs'][i], G['to'][i], G['kick'][i], G['lift'][i], G['flat'], G['run'])
        p['foot' + s] = [G['dx'][i], y, lift, pitch, G['yaw'][i], tw]
    cm, ob, pb, lg, ps = G['cm'], G['ob'], G['pbph'], G['lag'], G['ph0'][0] + 0.02
    lur, cy = G['lurch'], G['yawA'] * G['cr']
    p['hipofs'] = [G['sway'] * c(cm + 0.02), G['hy'] + G['fa'] * c(ob + 0.1, 2), dz + G['bob'] * c(ob, 2) + G['dip'] * c(cm)]
    p['root'] = [G['lean'] + G['pb'] * c(pb, 2), -G['drop'] * c(cm + 0.02), -G['yawA'] * c(ps)]
    p['spine'] = [G['spine'] + 0.4 * G['nod'] * c(pb + lg, 2), 0.45 * lur * c(cm + lg), 0.45 * cy * c(ps + lg)]
    p['chest'] = [G['chest'] + 0.6 * G['nod'] * c(pb + 2 * lg, 2), 0.55 * lur * c(cm + 2 * lg), 0.55 * cy * c(ps + 2 * lg)]
    troll = lur - G['drop']; tyaw = (G['cr'] - 1) * G['yawA']; hd = G['head']
    p['neck'] = [G['neck'] + 0.5 * G['hnod'] * c(pb + 3 * lg, 2), -0.3 * troll * c(cm + 3 * lg), -0.35 * tyaw * c(ps + 3 * lg)]
    p['head'] = [hd[0] + G['hnod'] * c(pb + 4.5 * lg, 2), hd[1] - 0.3 * troll * c(cm + 4 * lg) + G['hroll'] * c(cm + 6 * lg),
                 hd[2] - 0.3 * tyaw * c(ps + 5 * lg)]
    p['jaw'] = [G['jaw'] + 2.5 * c(pb + 6 * lg, 2)]
    for i, s in enumerate('LR'):
        a = G['arm' + s]; b = a['b']; fo = G['ph0'][1 - i] + a['lag']          # furthest forward a little after the opposite foot strikes
        sw = c(fo); bn = a['bn'] * c(pb + 0.12, 2)
        p['arm' + s] = [b[0] + a.get('dn', 0) * sw - 0.4 * bn, b[1] + a['sw'] * sw, b[2], b[3] + a['el'] * c(fo + 0.09) + bn,
                        b[4] + a.get('wr', 6) * c(fo + 0.2), b[5] + a.get('hz', 0) * sw]
        shb = G['sh' + s]
        p['sh' + s] = [shb[0] + 0.5 * bn, shb[1] + 0.2 * a['sw'] * sw]
    return p


def fit_height(G):
    """Pelvis height offset (walker metres) at which the straightest leg of the cycle reaches G['ext']."""
    lo, hi = -0.40, 0.15
    for _ in range(18):
        mid = 0.5 * (lo + hi)
        if max(leg_ext(gait(k / 60.0, G, mid)) for k in range(60)) > G['ext']:
            hi = mid
        else:
            lo = mid
    return lo


def make_gait(G):
    G['dz'] = fit_height(G)
    return lambda t: solve_ik(gait(t / G['T'], G, G['dz']))


