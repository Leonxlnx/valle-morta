"""Procedural animation clips (numpy FK / IK) -> <build>/anim.npz   |   ZVARIANT=<type> python anim.py

Rotations are stored per bone as local rotations expressed in character-space axes
(rest pose = identity for every bone): x = left, y = back, z = up.  The character faces -y.

Locomotion is generated by one gait model (gait()) driven by a style table per type:
  * each foot: heel strike -> flat -> heel-off roll over the ball -> toe-off, with the contact point pinned to a
    ground that moves back at exactly the clip's ground speed (no sliding by construction), then a swing whose
    start and end velocities match the ground,
  * pelvis: rise / fall, side sway over the stance leg, drop on the swing side, yaw with the stride; the height is
    fitted so the stance leg is never over-extended,
  * spine, chest, neck, head and arms follow with increasing phase lag (counter-rotating shoulders, head lag).
All lengths in the style tables are in walker metres and are scaled by the type's leg length.
"""
