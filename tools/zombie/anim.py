# ----------------------------------------------------------------------------- keyframe tracks
def track(keys):
    """keys: [(t, {param: value-list})] -> f(t) -> full param dict (Catmull-Rom, missing params carry forward).
    Foot entries are offsets from the type's base stance."""
    b0 = base(); cur = base(); ts = []; full = []
    for t, d in keys:
        cur = {k: list(v) for k, v in cur.items()}
        for k, v in d.items():
            v = list(v) if isinstance(v, (list, tuple)) else [v]
            cur[k] = [b + o for b, o in zip(b0[k], v + [0] * 6)] if k.startswith('foot') else v + list(b0[k])[len(v):]
        ts.append(t); full.append(cur)
    ts = np.array(ts, float)

    def f(t):
        t = float(np.clip(t, ts[0], ts[-1])); i = int(np.clip(np.searchsorted(ts, t, 'right') - 1, 0, len(ts) - 2))
        u = (t - ts[i]) / (ts[i + 1] - ts[i]); out = {}
        for k in full[0]:
            p1 = np.array(full[i][k], float); p2 = np.array(full[i + 1][k], float)
            m1 = (p2 - np.array(full[i - 1][k], float)) / (ts[i + 1] - ts[i - 1]) * (ts[i + 1] - ts[i]) if i > 0 else np.zeros_like(p1)
            m2 = (np.array(full[i + 2][k], float) - p1) / (ts[i + 2] - ts[i]) * (ts[i + 1] - ts[i]) if i + 2 < len(ts) else np.zeros_like(p1)
            h00 = 2 * u ** 3 - 3 * u ** 2 + 1; h10 = u ** 3 - 2 * u ** 2 + u; h01 = -2 * u ** 3 + 3 * u ** 2; h11 = u ** 3 - u ** 2
            out[k] = list(h00 * p1 + h10 * m1 + h01 * p2 + h11 * m2)
        return out
    return f


LAGS = dict(chest=0.012, neck=0.035, head=0.055, jaw=0.065, shL=0.015, shR=0.015, armL=0.045, armR=0.035, legL=0.015, legR=0.025)


def lagged(trk, t, k=1.0):
    """Overlapping action: the further out a part is, the later it follows the same keys."""
    p = trk(t)
    for key, lag in LAGS.items():
        p[key] = trk(t - lag * k)[key]
    return p


def add(p, k, v):
    p[k] = [a + b for a, b in zip(p[k], list(v) + [0] * 8)]


