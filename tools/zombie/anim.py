def bake():
    from scipy.spatial.transform import Rotation as Rot
    out = {}
    for name, fn, T, loop in CLIPS:
        n = int(round(T * FPS)) + 1
        hp_ = np.zeros((n, 3)); q = np.zeros((n, len(BONES), 4))
        for f in range(n):
            pos, L = fn(0.0 if (loop and f == n - 1) else f / FPS)
            hp_[f] = pos; q[f] = Rot.from_matrix(np.stack([L[b] for b in BONES])).as_quat()
            if f:
                flip = (q[f] * q[f - 1]).sum(1) < 0; q[f][flip] *= -1
        out[name + '_pos'] = hp_.astype(np.float32); out[name + '_rot'] = q.astype(np.float32)
    out['names'] = np.array([c[0] for c in CLIPS]); out['durations'] = np.array([c[2] for c in CLIPS]); out['bones'] = np.array(BONES); out['fps'] = FPS
    np.savez(os.path.join(variant.BUILD, 'anim.npz'), **out)
    return out


def plant_error(G):
    """Largest distance (m) of the stance contact point (ball, or heel while the toes are up) from where the moving ground puts it."""
    worst = 0.0
    for i, s in enumerate('LR'):
        a0, b0, h0 = foot_pivots(s)
        for k in range(100):
            ph = (G['ph0'][i] + (k + 0.5) / 100 * G['D'][i]) % 1.0
            p = gait(ph, G, G['dz']); P, W = fk(*solve_ik(p)); f = p['foot' + s]
            ofs = LS * np.array([f[0] * SD[s], f[1], 0.0])
            if f[3] >= 0:
                act = P[IDX['Toe.' + s]]; ref = b0 + ofs
            else:
                act = P[IDX['Foot.' + s]] + W[IDX['Foot.' + s]] @ (h0 - a0); ref = b0 + Rz(-SD[s] * f[4]) @ (h0 - b0) + ofs
            worst = max(worst, float(np.linalg.norm(act - ref)))
    return worst


def game_speed(fn, T):
    """The engine's own estimate (src/game/zombies.js _measureClips): backward speed of the supporting ankle."""
    N = 120; dt = T / N; ys = [[], []]; zs = [[], []]
    for i in range(N + 1):
        P, _ = fk(*fn(min(T * 0.9999, i * dt)))
        for k, s in enumerate('LR'):
            a = P[IDX['Foot.' + s]]; ys[k].append(a[2]); zs[k].append(-a[1])
    v = sorted((zs[f][i] - zs[f][i + 1]) / dt for i in range(N) for f in [0 if ys[0][i] + ys[0][i + 1] <= ys[1][i] + ys[1][i + 1] else 1])
    planted = back = 0.0
    for f in range(2):
        ymin = min(ys[f])
        for i in range(N):
            if ys[f][i] < ymin + 0.03 and ys[f][i + 1] < ymin + 0.03:
                planted += dt; back += zs[f][i] - zs[f][i + 1]
    stance = planted / (2 * T)
    return (v[N >> 1] if stance >= 0.4 or planted <= 0 else back / planted), stance


