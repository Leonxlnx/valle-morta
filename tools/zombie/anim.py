def base():
    """The type's neutral slump. Every clip starts from / returns to this."""
    p = dict(root=[0, 0, 0], hipofs=[0, 0, -0.03], spine=[5, 0, 0], chest=[8, 0, 0], neck=[14, 0, 0], head=[-8, 9, -5], jaw=[6],
             shL=[-5, 4], shR=[3, 6], armL=[38, 6, 0, 16, 10, 0], armR=[30, 12, 0, 28, 14, 0],
             footL=[0, 0, 0, 0, 0, 1], footR=[0, 0, 0, 0, 8, 1],        # dx, dy, lift, pitch(+ = heel up), yaw-in, toe bend weight
             legL=[0, 0, 0, 0, 0, 0, 0], legR=[0, 0, 0, 0, 0, 0, 0], fk=[0.0])   # FK legs: thigh xyz, knee, foot x z, toe
    for k, v in POSE.items():
        p[k] = list(v)
    return p


def upper_locals(p):
    L = {b: np.eye(3) for b in BONES}
    L['Hips'] = E(*p['root']); L['Spine'] = E(*p['spine']); L['Chest'] = E(*p['chest'])
    L['Neck'] = E(*p['neck']); L['Head'] = E(*p['head']); L['Jaw'] = Rx(p['jaw'][0])
    for s in 'LR':
        sd = SD[s]; up, fw = p['sh' + s]
        L['Shoulder.' + s] = Ry(-sd * up) @ Rz(-sd * fw)
        down, fwd, tw, elb, wr, hz = p['arm' + s]
        L['UpperArm.' + s] = Rx(-fwd) @ Rz(sd * hz) @ Ry(sd * down) @ aa(ARMDIR[s], tw * sd)
        L['LowerArm.' + s] = aa(ELBOW[s], elb)
        L['Hand.' + s] = aa(ELBOW[s], wr)
    return L


def fk(hips_pos, L):
    W = [None] * len(BONES); P = np.zeros((len(BONES), 3))
    for i, b in enumerate(BONES):
        pa = PARENT[i]
        if pa < 0:
            W[i] = L[b]; P[i] = hips_pos
        else:
            W[i] = W[pa] @ L[b]; P[i] = P[pa] + W[pa] @ (REST[i] - REST[pa])
    return P, W


def frame(d, f):
    d = unit(d); f = np.asarray(f, float); f = unit(f - d * (f @ d))
    return np.stack([d, f, np.cross(d, f)], 1)


def foot_pivots(s):
    a0 = REST[IDX['Foot.' + s]]; b0 = REST[IDX['Toe.' + s]]
    return a0, b0, a0 * [1, 1, 0] + np.array([0, 0.07, 0.008]) * FS          # ankle, ball, heel contact


def foot_target(s, dx, dy, lift, pitch, yaw=0.0):
    """Ankle position: the foot rolls about the ball (heel up) or the heel (toe up) and turns about the ball."""
    a0, b0, h0 = foot_pivots(s)
    piv = b0 if pitch >= 0 else h0
    au = piv + Rx(pitch) @ (a0 - piv)
    return b0 + Rz(-SD[s] * yaw) @ (au - b0) + LS * np.array([dx * SD[s], dy, lift])


def leg_ik(L, s, hips_pos, target, pitch, yaw_in, toe_w=1.0, pole=(0, -1, 0.0)):
    W_h = L['Hips']
    iu, il, ift = IDX['UpperLeg.' + s], IDX['LowerLeg.' + s], IDX['Foot.' + s]
    hip = hips_pos + W_h @ (REST[iu] - REST[0])
    t1 = REST[il] - REST[iu]; t2 = REST[ift] - REST[il]
    L1, L2 = np.linalg.norm(t1), np.linalg.norm(t2)
    v = target - hip; dist = min(max(np.linalg.norm(v), 0.12 * LS), L1 + L2 - 1e-4); vd = unit(v)
    pole = np.asarray(pole, float) + np.array([KNEE_OUT * SD[s], 0, 0]); pole = unit(pole - vd * (pole @ vd))
    ch = (L1 * L1 + dist * dist - L2 * L2) / (2 * L1 * dist); sh = np.sqrt(max(1 - ch * ch, 0))
    td = vd * ch + pole * sh
    knee = hip + td * L1
    sdir = unit(hip + vd * dist - knee)
    Wt = frame(td, pole) @ frame(t1, [0, -1, 0]).T
    Ws = frame(sdir, pole) @ frame(t2, [0, -1, 0]).T
    Wf = Rz(-SD[s] * yaw_in) @ Rx(pitch)
    L['UpperLeg.' + s] = W_h.T @ Wt; L['LowerLeg.' + s] = Wt.T @ Ws; L['Foot.' + s] = Ws.T @ Wf
    L['Toe.' + s] = Rx(-min(max(pitch, 0.0), 50.0) * toe_w)


def solve_ik(p):
    L = upper_locals(p)
    hp_ = REST[0] + LS * np.asarray(p['hipofs'], float)
    for s in 'LR':
        dx, dy, lift, pitch, yaw, tw = (list(p['foot' + s]) + [1.0])[:6]
        leg_ik(L, s, hp_, foot_target(s, dx, dy, lift, pitch, yaw), pitch, yaw, tw)
    return hp_, L


def leg_ext(p):
    """Largest hip-to-ankle distance relative to the leg length (1 = fully straight)."""
    Wh = E(*p['root']); hp_ = REST[0] + LS * np.asarray(p['hipofs'], float); m = 0.0
    for s in 'LR':
        f = p['foot' + s]
        hip = hp_ + Wh @ (REST[IDX['UpperLeg.' + s]] - REST[0])
        m = max(m, float(np.linalg.norm(foot_target(s, f[0], f[1], f[2], f[3], f[4]) - hip)) / LEGLEN[s])
    return m


def blend(A, B, w):
    """Geodesic blend of rotation matrices."""
    from scipy.spatial.transform import Rotation as Rot
    return A @ Rot.from_rotvec(Rot.from_matrix(A.T @ B).as_rotvec() * w).as_matrix()


