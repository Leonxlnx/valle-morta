def twitch(t, t0, T, tau=0.07):
    u = (t - t0) % T
    return (u / tau) * np.exp(1 - u / tau)


IDLE_T = 3.0
BREATH = {'walker': 1.0, 'runner': 1.5, 'brute': 1.6, 'boss': 1.9}[V]


def idle(t, T=IDLE_T):
    p = base(); w = 2 * pi * t / T; s1, s2, s3 = np.sin(w), np.sin(2 * w), np.sin(3 * w); c1 = 1 - np.cos(w); c2 = 1 - np.cos(2 * w)
    s1l, s1ll = np.sin(w - 0.5), np.sin(w - 1.0)                                    # the upper body trails the hips
    tw1 = twitch(t, 0.8, T); tw2 = twitch(t, 1.9, T, 0.09); tw3 = twitch(t, 2.35, T, 0.06)
    add(p, 'hipofs', [0.021 * s1, 0.006 * s2, -0.004 * c2 - 0.004 * c1])            # weight drifts from foot to foot
    add(p, 'root', [0.8 * s2, -1.6 * s1, 1.2 * s1 + 0.5 * s3])
    add(p, 'spine', [1.0 * s2 - 0.6 * BREATH * c2, 1.6 * s1l, 1.0 * s1l]); add(p, 'chest', [-1.3 * BREATH * c2 + 0.8 * s1l, 1.4 * s1ll, 1.6 * s3 + 2.0 * tw2])
    add(p, 'neck', [2.0 * s2 - 1.5 * c1 + 0.8 * BREATH * c2, 1.2 * s1ll, 2.0 * s3 + 2.5 * tw1])
    add(p, 'head', [2.5 * s3 - 3.5 * tw2 + 2.5 * tw3, 2.5 * c1 - 4 * tw1 + 3 * tw3 - 1.5 * s1ll, 3 * s2 + 7 * tw1 - 6 * tw2])
    add(p, 'jaw', [2.5 * c1 + 4 * tw2 + 2 * tw1])
    add(p, 'shL', [0.9 * BREATH * c2 + 3 * tw2, 0]); add(p, 'shR', [0.8 * BREATH * c2 + 5 * tw2, 0])
    add(p, 'armL', [1.5 * s1l, 3 * np.sin(2 * w - 0.9), 0, 2 * c1 + 2.5 * tw2, 2 * s3, 0]); add(p, 'armR', [-1.5 * s1l, 3.5 * np.sin(3 * w - 0.8), 0, 3 * c2 + 4 * tw2, -2 * s2, 0])
    return solve_ik(p)


# ----------------------------------------------------------------------------- locomotion
def _foot(u, D, yf, st, ps, to, kick, H, flat, run=False):
    """One foot over the cycle, u = phase since its strike. -> y, lift, pitch, toe bend weight."""
    if u < D:
        q = u / D
        return yf + st * u, 0.0, ps * (1 - sstep(0.0, flat[0], q)) + to * sstep(flat[1], 1.0, q), 1.0
    q = (u - D) / (1 - D); m = st * (1 - D); qa = 0.86 if run else 0.92               # leaves the ground at ground speed ...
    if q < qa:
        r = q / qa
        h00 = 2 * r ** 3 - 3 * r ** 2 + 1; h10 = r ** 3 - 2 * r ** 2 + r; h01 = -2 * r ** 3 + 3 * r ** 2; h11 = r ** 3 - r ** 2
        y = h00 * (yf + st * D) + h10 * m * qa + h01 * (yf - m * (1 - qa)) + h11 * m * qa
    else:
        y = yf - m * (1 - q)                                                          # ... and is already moving with it as it comes down
    lift = H * np.sin(pi * q ** 0.85) if run else H * 0.5 * (1 - np.cos(2 * pi * q ** 0.85))
    b = sstep(0.30, 0.94, q)
    pitch = (to + (kick - to) * sstep(0.0, 0.32, q)) * (1 - b) + ps * b
    return y, lift, pitch, 1 - 0.75 * sstep(0.0, 0.25, q) * (1 - sstep(0.8, 1.0, q))


