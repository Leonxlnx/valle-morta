// Interface: loading screen, main menu, settings, pause, HUD and the summary
// screen. Plain DOM, one typeface, neutral palette.
const DEFAULTS = {
  quality: 'high', renderScale: 1, fov: 72, sensitivity: 1, invertY: false,
  master: 0.8, music: 0.55, sfx: 0.9, grain: true, showFps: false,
};

export function loadSettings() {
  try { return { ...DEFAULTS, ...JSON.parse(localStorage.getItem('valle-morta-settings') || '{}') }; } catch (e) { return { ...DEFAULTS }; }
}
function saveSettings(s) { try { localStorage.setItem('valle-morta-settings', JSON.stringify(s)); } catch (e) { /* private mode */ } }

const el = (tag, cls, html) => { const e = document.createElement(tag); if (cls) e.className = cls; if (html !== undefined) e.innerHTML = html; return e; };
const fmtTime = (t) => `${Math.floor(t / 60)}:${String(Math.floor(t % 60)).padStart(2, '0')}`;

export class UI {
  constructor(root, settings, handlers) {
    this.root = root; this.settings = settings; this.h = handlers;
    this.state = 'loading';
    root.innerHTML = '';

    // ---- loading
    this.loading = el('section', 'screen loading show', `
      <div class="load-box">
        <h1 class="wordmark">Valle Morta</h1>
        <div class="bar"><i></i></div>
        <p class="load-note">Preparing the valley</p>
      </div>`);

    // ---- menu
    this.menu = el('section', 'screen menu', `
      <div class="menu-col">
        <h1 class="wordmark big">Valle Morta</h1>
        <p class="lede">The war emptied this valley. Something else moved in. Hold the ruins for as long as you can.</p>
        <nav class="menu-nav">
          <button class="btn primary" data-act="play">Play</button>
          <button class="btn" data-act="settings">Settings</button>
          <button class="btn" data-act="howto">How to play</button>
        </nav>
      </div>
      <p class="foot">Every stone, blade of grass and texture in this world is generated by code.</p>`);

    // ---- pause
    this.pause = el('section', 'screen pause', `
      <div class="sheet">
        <h2>Paused</h2>
        <nav class="menu-nav">
          <button class="btn primary" data-act="resume">Resume</button>
          <button class="btn" data-act="settings">Settings</button>
          <button class="btn" data-act="quit">Leave the valley</button>
        </nav>
      </div>`);

    // ---- game over
    this.over = el('section', 'screen over', `
      <div class="sheet">
        <h2>You fell in the valley</h2>
        <dl class="stats"></dl>
        <nav class="menu-nav">
          <button class="btn primary" data-act="play">Try again</button>
          <button class="btn" data-act="quit">Main menu</button>
        </nav>
      </div>`);

    // ---- how to play
    this.howto = el('section', 'screen panel', `
      <div class="sheet wide">
        <h2>How to play</h2>
        <dl class="keys">
          <div><dt>Move</dt><dd>W A S D</dd></div>
          <div><dt>Look</dt><dd>Mouse</dd></div>
          <div><dt>Fire</dt><dd>Left mouse button</dd></div>
          <div><dt>Aim down sights</dt><dd>Right mouse button</dd></div>
          <div><dt>Reload</dt><dd>R</dd></div>
          <div><dt>Sprint</dt><dd>Shift</dd></div>
          <div><dt>Jump</dt><dd>Space</dd></div>
          <div><dt>Crouch</dt><dd>Ctrl or C</dd></div>
          <div><dt>Pause</dt><dd>Esc</dd></div>
        </dl>
        <p class="hint">A new wave leaves the village a few seconds after the last one falls. Head shots put them down for good; ammunition is resupplied between waves. Music by Kevin MacLeod (incompetech.com), licensed under CC BY 4.0.</p>
        <nav class="menu-nav row"><button class="btn" data-act="back">Back</button></nav>
      </div>`);

    // ---- settings
    this.settingsEl = el('section', 'screen panel', `
      <div class="sheet wide">
        <h2>Settings</h2>
        <div class="rows">
          <h3>Graphics</h3>
          <div class="row"><span>Quality</span>
            <span class="seg" data-key="quality">
              <button type="button" data-v="low">Low</button><button type="button" data-v="medium">Medium</button><button type="button" data-v="high">High</button><button type="button" data-v="ultra">Ultra</button>
            </span></div>
          <label class="row"><span>Render scale</span><input type="range" min="0.5" max="1" step="0.05" data-key="renderScale"><output></output></label>
          <label class="row"><span>Field of view</span><input type="range" min="60" max="95" step="1" data-key="fov"><output></output></label>
          <label class="row"><span>Film grain</span><input type="checkbox" data-key="grain"></label>
          <label class="row"><span>Show frame rate</span><input type="checkbox" data-key="showFps"></label>
          <h3>Controls</h3>
          <label class="row"><span>Mouse sensitivity</span><input type="range" min="0.2" max="2.5" step="0.05" data-key="sensitivity"><output></output></label>
          <label class="row"><span>Invert vertical look</span><input type="checkbox" data-key="invertY"></label>
          <h3>Audio</h3>
          <label class="row"><span>Master volume</span><input type="range" min="0" max="1" step="0.01" data-key="master"><output></output></label>
          <label class="row"><span>Music</span><input type="range" min="0" max="1" step="0.01" data-key="music"><output></output></label>
          <label class="row"><span>Effects</span><input type="range" min="0" max="1" step="0.01" data-key="sfx"><output></output></label>
        </div>
        <nav class="menu-nav row"><button class="btn" data-act="back">Back</button></nav>
      </div>`);

    // ---- HUD
    this.hud = el('section', 'hud', `
      <div class="cross"><i></i><i></i><i></i><i></i><b></b></div>
      <div class="hitmark"><i></i><i></i><i></i><i></i></div>
      <div class="vitals"><span class="hp-num">100</span><div class="hp"><i></i></div></div>
      <div class="ammo"><span class="mag">30</span><span class="res">120</span></div>
      <div class="status"></div>
      <div class="toast"><strong></strong><span></span></div>
      <div class="prompt"></div>
      <div class="hurt"></div>
      <div class="fps"></div>`);

    root.append(this.hud, this.menu, this.pause, this.over, this.howto, this.settingsEl, this.loading);
    this.q = (s, p = this.hud) => p.querySelector(s);
    this.cross = this.q('.cross'); this.hitEl = this.q('.hitmark'); this.hpNum = this.q('.hp-num'); this.hpBar = this.q('.hp i');
    this.mag = this.q('.mag'); this.res = this.q('.res'); this.status = this.q('.status'); this.toastEl = this.q('.toast');
    this.prompt = this.q('.prompt'); this.hurtEl = this.q('.hurt'); this.fpsEl = this.q('.fps');
    this.hurtV = 0; this.hitT = 0; this.toastT = 0; this.back = 'menu';
    this._last = {};

    root.addEventListener('click', (e) => {
      const b = e.target.closest('[data-act]');
      if (!b) return;
      const act = b.dataset.act;
      this.h.click?.();
      if (act === 'play') this.h.play();
      else if (act === 'resume') this.h.resume();
      else if (act === 'quit') this.h.quit();
      else if (act === 'settings') { this.back = this.state; this.show(this.settingsEl); }
      else if (act === 'howto') { this.back = this.state; this.show(this.howto); }
      else if (act === 'back') this.setState(this.back, this._summary);
    });
    this._bindSettings();
  }

  _bindSettings() {
    const s = this.settings, root = this.settingsEl;
    const fmt = { renderScale: (v) => `${Math.round(v * 100)}%`, fov: (v) => `${v}°`, sensitivity: (v) => Number(v).toFixed(2), master: (v) => `${Math.round(v * 100)}`, music: (v) => `${Math.round(v * 100)}`, sfx: (v) => `${Math.round(v * 100)}` };
    const sync = () => {
      root.querySelectorAll('[data-key]').forEach((c) => {
        const k = c.dataset.key;
        if (c.classList.contains('seg')) c.querySelectorAll('button').forEach((b) => b.classList.toggle('on', b.dataset.v === s[k]));
        else if (c.type === 'checkbox') c.checked = !!s[k];
        else { c.value = s[k]; const o = c.parentElement.querySelector('output'); if (o) o.textContent = fmt[k] ? fmt[k](s[k]) : s[k]; }
      });
    };
    root.addEventListener('input', (e) => {
      const c = e.target; const k = c.dataset.key; if (!k) return;
      s[k] = c.type === 'checkbox' ? c.checked : Number(c.value);
      saveSettings(s); sync(); this.h.settings?.(k);
    });
    root.addEventListener('click', (e) => {
      const b = e.target.closest('.seg button'); if (!b) return;
      e.preventDefault();
      const k = b.parentElement.dataset.key; s[k] = b.dataset.v;
      saveSettings(s); sync(); this.h.settings?.(k);
    });
    sync();
  }

  show(screen) {
    for (const s of [this.loading, this.menu, this.pause, this.over, this.howto, this.settingsEl]) s.classList.toggle('show', s === screen);
  }

  progress(p, note) {
    this.loading.querySelector('.bar i').style.transform = `scaleX(${Math.max(0.02, Math.min(1, p))})`;
    if (note) this.loading.querySelector('.load-note').textContent = note;
  }

  setState(state, summary) {
    this.state = state;
    this._summary = summary;
    this.hud.classList.toggle('show', state === 'playing' || state === 'paused');
    document.body.classList.toggle('in-game', state === 'playing');
    if (state === 'menu') this.show(this.menu);
    else if (state === 'paused') this.show(this.pause);
    else if (state === 'playing') this.show(null);
    else if (state === 'over') {
      const s = summary || {};
      this.over.querySelector('.stats').innerHTML = `
        <div><dt>Wave reached</dt><dd>${s.wave ?? 0}</dd></div>
        <div><dt>Infected put down</dt><dd>${s.kills ?? 0}</dd></div>
        <div><dt>Head shots</dt><dd>${s.headshots ?? 0}</dd></div>
        <div><dt>Accuracy</dt><dd>${s.accuracy ?? 0}%</dd></div>
        <div><dt>Time survived</dt><dd>${fmtTime(s.time ?? 0)}</dd></div>`;
      this.show(this.over);
    } else if (state === 'hidden') this.show(null);
  }

  toast(title, sub) {
    this.toastEl.querySelector('strong').textContent = title;
    this.toastEl.querySelector('span').textContent = sub || '';
    this.toastEl.classList.add('on');
    this.toastT = 3.6;
  }

  hitMarker(kill, head) {
    this.hitEl.classList.remove('on', 'kill');
    void this.hitEl.offsetWidth;
    this.hitEl.classList.add('on');
    if (kill) this.hitEl.classList.add('kill');
  }

  hurt() { this.hurtV = Math.min(1, this.hurtV + 0.55); }

  update(game, dt) {
    if (this.state !== 'playing') return;
    const p = game.player, w = game.weapon, L = this._last;
    const set = (key, val, fn) => { if (L[key] !== val) { L[key] = val; fn(val); } };
    set('hp', Math.ceil(p.health), (v) => { this.hpNum.textContent = v; this.hpBar.style.transform = `scaleX(${v / 100})`; this.hud.classList.toggle('low', v <= 35); });
    set('mag', w.ammo, (v) => { this.mag.textContent = v; this.mag.classList.toggle('empty', v <= 5); });
    set('res', w.reserve, (v) => { this.res.textContent = v; });
    set('status', `${game.wave}|${game.stats.kills}`, () => { this.status.textContent = game.wave ? `Wave ${game.wave} · ${game.stats.kills} down` : ''; });
    // crosshair opens with movement / fire, hides while aiming or sprinting
    const spread = 7 + Math.min(1, p.speed / 6) * 9 + Math.min(5, w.burst) * 2.2 + (p.onGround ? 0 : 10);
    this.cross.style.setProperty('--s', `${spread.toFixed(1)}px`);
    this.cross.style.opacity = String(Math.max(0, 1 - p.adsT * 1.6) * (w.reloading || p.sprinting ? 0.25 : 0.9) * (p.alive ? 1 : 0));
    this.hurtV = Math.max(0, this.hurtV - dt * 0.9);
    const low = p.health < 40 ? (40 - p.health) / 40 * 0.55 : 0;
    this.hurtEl.style.opacity = String(Math.min(1, this.hurtV + low));
    if (this.toastT > 0) { this.toastT -= dt; if (this.toastT <= 0) this.toastEl.classList.remove('on'); }
    let prompt = '';
    if (!p.alive) prompt = '';
    else if (!p.script && document.pointerLockElement !== game.engine.canvas) prompt = 'Click to take aim';
    else if (p.boundary > 0.3) prompt = 'Turn back — the valley is sealed beyond this point';
    else if (w.reloading) prompt = 'Reloading';
    else if (w.ammo === 0 && w.reserve === 0) prompt = 'Out of ammunition — hold on until the next wave';
    else if (w.ammo <= 5) prompt = 'Press R to reload';
    set('prompt', prompt, (v) => { this.prompt.textContent = v; this.prompt.classList.toggle('on', !!v); });
    if (this.settings.showFps) { this.fpsEl.textContent = `${Math.round(game.fps || 0)} fps`; this.fpsEl.style.display = 'block'; } else if (L.fpsHidden !== true) { this.fpsEl.style.display = 'none'; L.fpsHidden = true; }
    if (this.settings.showFps) L.fpsHidden = false;
  }
}
