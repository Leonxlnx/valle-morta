  _bindSettings() {
    const s = this.settings, root = this.settingsEl;
    const fmt = { renderScale: (v) => `${Math.round(v * 100)}%`, fov: (v) => `${v}°`, sensitivity: (v) => Number(v).toFixed(2), master: (v) => `${Math.round(v * 100)}`, music: (v) => `${Math.round(v * 100)}`, sfx: (v) => `${Math.round(v * 100)}` };
    const sync = () => {
      root.querySelectorAll('[data-key]').forEach((c) => {
        const k = c.dataset.key;
        if (c.classList.contains('seg')) c.querySelectorAll('button').forEach((b) => b.classList.toggle('on', b.dataset.v === s[k]));
        else if (c.type === 'checkbox') c.checked = !!s[k];
        else {
          c.value = s[k];
          c.style.setProperty('--v', `${(((s[k] - c.min) / (c.max - c.min)) * 100).toFixed(1)}%`);
          const o = c.parentElement.querySelector('output'); if (o) o.textContent = fmt[k] ? fmt[k](s[k]) : s[k];
        }
      });
    };
    root.addEventListener('input', (e) => {
      const c = e.target; const k = c.dataset.key; if (!k) return;
      s[k] = c.type === 'checkbox' ? c.checked : Number(c.value);
      saveSettings(s); sync(); this.h.settings?.(k);
    });
    root.addEventListener('click', (e) => {
      const b = e.target.closest('.seg button'); if (!b) return;
      e.preventDefault();
      const k = b.parentElement.dataset.key; s[k] = b.dataset.v;
      saveSettings(s); sync(); this.h.settings?.(k);
    });
    sync();
  }

  show(screen) {
    for (const s of [this.loading, this.menu, this.pause, this.over, this.debrief, this.baseScreen.el, this.howto, this.settingsEl]) s.classList.toggle('show', s === screen);
  }

  progress(p, note) {
    this.loading.querySelector('.bar i').style.transform = `scaleX(${Math.max(0.02, Math.min(1, p))})`;
    if (note) this.loading.querySelector('.load-note').textContent = note;
  }

  setState(state, summary) {
    this.state = state;
    this._summary = summary;
    this.hud.classList.toggle('show', state === 'playing' || state === 'paused');
    document.body.classList.toggle('in-game', state === 'playing');
    if (state === 'menu') {
      const p = this.profile, d = p && p.data;
      if (d && d.totals && d.totals.runs) this.menu.querySelector('.op-meta').textContent = `${fmtN(p.salvage)} salvage banked · best wave ${d.best.wave}`;
      this.show(this.menu);
    } else if (state === 'paused') {
      const g = this.game;
      this.pause.querySelector('.sub').textContent = g && g.wave ? `Wave ${g.wave} · ${g.stats.kills} down · ${fmtTime(g.playTime || 0)}` : 'The valley waits.';
      this.show(this.pause);
    } else if (state === 'playing') this.show(null);
    else if (state === 'over') {
      const s = summary || {};
      this.over.querySelector('.stats').innerHTML = `
        <div><dt>Wave reached</dt><dd>${s.wave ?? 0}</dd></div>
        <div><dt>Infected put down</dt><dd>${s.kills ?? 0}</dd></div>
        <div><dt>Head shots</dt><dd>${s.headshots ?? 0}</dd></div>
        <div><dt>Accuracy</dt><dd>${s.accuracy ?? 0}%</dd></div>
        <div><dt>Time survived</dt><dd>${fmtTime(s.time ?? 0)}</dd></div>`;
      this.show(this.over);
    } else if (state === 'base') {
      this.baseScreen.open();
      this.show(this.baseScreen.el);
    } else if (state === 'debrief') {
      const s = summary || {}, out = s.outcome === 'extract', diff = Math.abs((s.banked ?? 0) - (s.earned ?? 0));
      this.debrief.querySelector('h2').textContent = out ? 'Extracted' : s.outcome === 'abandon' ? 'Run abandoned' : 'You fell in the valley';
      this.debrief.querySelector('.sub').textContent = out ? 'Everything you gathered came out with you, and a premium on top.' : 'Half of what you gathered found its way back to Base.';
      this.debrief.querySelector('.stats').innerHTML = `
        <div><dt>Wave reached</dt><dd>${s.wave ?? 0}</dd></div>
        <div><dt>Waves cleared</dt><dd>${s.cleared ?? 0}</dd></div>
        <div><dt>Infected put down</dt><dd>${s.kills ?? 0}</dd></div>
        <div><dt>Head shots</dt><dd>${s.headshots ?? 0}</dd></div>
        <div><dt>Salvage gathered</dt><dd>${s.earned ?? 0}</dd></div>
        <div><dt>${out ? 'Extraction bonus' : 'Lost in the valley'}</dt><dd>${out ? '+' : '−'}${diff}</dd></div>
        <div class="sum"><dt>Banked</dt><dd>${s.banked ?? 0}</dd></div>`;
      this.show(this.debrief);
    } else if (state === 'hidden') this.show(null);
  }

